import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve('docs/public/access-log-analysis');
mkdirSync(path.join(root, 'samples'), { recursive: true });
writeFileSync(
  path.join(root, 'lesson.md'),
  readFileSync('docs/access-log-analysis/index.md', 'utf8'),
);
let serial = 0;
function row(minute, second, ip, route, status = 200, extra = {}) {
  return {
    time: `2026-11-01T09:${String(minute).padStart(2, '0')}:${String(second).padStart(2, '0')}Z`,
    client_ip: ip,
    method: 'GET',
    path: route,
    status,
    user_agent: 'LearningBrowser/1.0',
    request_id: `req-${String(++serial).padStart(4, '0')}`,
    event: 'access',
    ...extra,
  };
}
const baseline = Array.from({ length: 60 }, (_, i) =>
  row(
    Math.floor(i / 6),
    (i % 6) * 10,
    `192.0.2.${(i % 3) + 1}`,
    ['/', '/help', '/products'][i % 3],
  ),
);
const scan = Array.from({ length: 30 }, (_, i) =>
  row(3, i * 2, '203.0.113.10', ['/admin', '/backup.zip', '/.env'][i % 3], 404),
);
const typo = Array.from({ length: 24 }, (_, i) =>
  row(6, i * 2, '198.51.100.20', '/old-help', 404),
);
const auth = Array.from({ length: 12 }, (_, i) =>
  row(4, i * 4, '203.0.113.40', '/login', 401, {
    method: 'POST',
    event: 'auth',
    account: 'learner-a',
    outcome: 'failure',
  }),
);
auth.push(
  row(4, 52, '203.0.113.40', '/login', 200, {
    method: 'POST',
    event: 'auth',
    account: 'learner-a',
    outcome: 'success',
  }),
);
const crawler = Array.from({ length: 40 }, (_, i) =>
  row(2, i, '198.51.100.30', `/articles/${i % 10}`, 200, {
    user_agent: 'LearningCrawler/1.0',
  }),
);
const shared = Array.from({ length: 20 }, (_, i) =>
  row(7, i * 2, '192.0.2.200', ['/help', '/products'][i % 2], 200, {
    user_agent: `LearningBrowser/${(i % 2) + 1}.0`,
  }),
);
const payload = Array.from({ length: 3 }, (_, i) =>
  row(
    8,
    i * 15,
    '203.0.113.60',
    [
      '/search?q=%27%20OR%201%3D1--',
      '/download?file=..%2F..%2Fetc%2Fpasswd',
      '/search?q=%3Cscript%3Ealert(1)%3C%2Fscript%3E',
    ][i],
    [200, 403, 200][i],
  ),
);
const distributed = Array.from({ length: 18 }, (_, i) =>
  row(5, i * 3, `203.0.113.${70 + (i % 6)}`, '/login', 401, {
    method: 'POST',
    event: 'auth',
    account: 'learner-b',
    outcome: 'failure',
  }),
);
const samples = {
  baseline,
  guided: [...baseline, ...scan, ...typo],
  challenge: [
    ...baseline,
    ...auth,
    ...crawler,
    ...shared,
    ...payload,
    ...distributed,
  ],
};
const embedded = {};
for (const [index, [name, records]] of Object.entries(samples).entries()) {
  records.sort((a, b) => a.time.localeCompare(b.time));
  const source = `${records.map((record) => JSON.stringify(record)).join('\n')}\n`;
  writeFileSync(
    path.join(root, 'samples', `0${index + 1}-${name}.jsonl`),
    source,
  );
  embedded[name] = source;
}
writeFileSync(
  path.join(root, 'samples.js'),
  `// Generated by npm run package:log-analysis\nglobalThis.LogSamples = ${JSON.stringify(embedded, null, 2)};\n`,
);
// Python standard library only. Fixed timestamps make the ZIP reproducible.
execFileSync(process.platform === 'win32' ? 'python' : 'python3', [
  '-c',
  `
from pathlib import Path
from zipfile import ZipFile, ZipInfo, ZIP_DEFLATED
root = Path('docs/public/access-log-analysis')
with ZipFile(root / 'access-log-analysis.zip', 'w') as archive:
    for source in sorted(root.rglob('*')):
        if not source.is_file() or source.suffix == '.zip':
            continue
        info = ZipInfo('access-log-analysis/' + source.relative_to(root).as_posix(), (2026, 11, 1, 0, 0, 0))
        info.compress_type = ZIP_DEFLATED
        archive.writestr(info, source.read_bytes())
`,
]);
console.log(
  `Packaged ${Object.values(samples).reduce((sum, rows) => sum + rows.length, 0)} sample records and offline tool.`,
);
// Fail early if the expected browser assets were accidentally omitted.
for (const name of [
  'analyzer.html',
  'core.js',
  'app.js',
  'style.css',
  'README.txt',
])
  readFileSync(path.join(root, name));
